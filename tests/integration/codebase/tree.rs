//! Integration test of the `rex codebase` tree: what it lists, what it prints
//! and what it writes to `CODEBASE.md`.

use std::fs;
use std::path::Path;

use assert_cmd::Command;
use tempfile::{TempDir, tempdir};

/// Writes each `(path, contents)` pair into a new temp dir.
fn write_tree(files: &[(&str, &str)]) -> TempDir {
    let dir = tempdir().expect("create tempdir");
    for (path, contents) in files {
        let file = dir.path().join(path);
        fs::create_dir_all(file.parent().expect("fixture has a parent")).expect("create dirs");
        fs::write(file, contents).expect("write fixture");
    }
    dir
}

/// Runs `rex codebase` with `args` in `dir` and returns what it printed.
fn codebase(dir: &Path, args: &[&str]) -> String {
    let assert = Command::cargo_bin("rex")
        .expect("find rex binary")
        .arg("codebase")
        .args(args)
        .current_dir(dir)
        .assert()
        .success();
    String::from_utf8(assert.get_output().stdout.clone()).expect("utf8 stdout")
}

fn codebase_md(dir: &Path) -> String {
    fs::read_to_string(dir.join("CODEBASE.md")).expect("read CODEBASE.md")
}

#[test]
fn codebase_golden_tree_honors_gitignore() {
    let dir = write_tree(&[
        ("src/main.rs", "fn main() {}\n"),
        ("docs/notes.md", "notes\n"),
        ("target/junk.o", "junk"),
        (".hidden", "secret"),
        (".gitignore", "/target\n"),
    ]);

    codebase(dir.path(), &["--for-human"]);

    let expected = "# Codebase\n\n\
        ```text\n\
        docs/\n\
        \x20\x20notes.md\n\
        src/\n\
        \x20\x20main.rs\n\
        ```\n\n\
        Generated by `rex codebase --for-human`.\n";
    assert_eq!(codebase_md(dir.path()), expected);

    codebase(dir.path(), &["--for-human"]);
    assert_eq!(
        codebase_md(dir.path()),
        expected,
        "a second run must not put CODEBASE.md in its own tree"
    );

    // The plain form prints, writes nothing, and lists a CODEBASE.md that a
    // project keeps in git, because only the run that writes it leaves it out.
    let plain = write_tree(&[("readme.txt", "hello\n"), ("src/main.rs", "fn main() {}\n")]);
    assert_eq!(codebase(plain.path(), &[]), "readme.txt\nsrc/\n  main.rs\n");
    assert!(
        !plain.path().join("CODEBASE.md").exists(),
        "the plain command wrote a file"
    );
    fs::write(plain.path().join("CODEBASE.md"), "# kept in git\n").expect("write CODEBASE.md");
    assert_eq!(
        codebase(plain.path(), &[]),
        "CODEBASE.md\nreadme.txt\nsrc/\n  main.rs\n"
    );
    assert_eq!(codebase_md(plain.path()), "# kept in git\n");

    // The footer names the flags in one order, whatever order was typed.
    // Each case: the arguments, the file, its contents, the tree and the footer.
    let footers: &[(&[&str], &str, &str, &str, &str)] = &[
        (
            &["--with-context", "--only", "rust", "--for-human"],
            "src/main.rs",
            "//! Entry point. Runs the tool.\nfn main() {}\n",
            "src/\n  main.rs - Entry point.\n",
            "--for-human --only rust --with-context",
        ),
        (
            &["--with-context", "--only", "go", "--for-human"],
            "src/feed.go",
            "// Reads the feed.\n\npackage feed\n",
            "src/\n  feed.go - Reads the feed.\n",
            "--for-human --only go --with-context",
        ),
    ];
    for (args, path, contents, tree, flags) in footers {
        let dir = write_tree(&[(path, contents)]);
        codebase(dir.path(), args);
        assert_eq!(
            codebase_md(dir.path()),
            format!("# Codebase\n\n```text\n{tree}```\n\nGenerated by `rex codebase {flags}`.\n"),
            "footer for {args:?}"
        );
    }
}
